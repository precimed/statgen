test_that("ID matching orients both loaders and survives cache round-trips", {
  root <- tempfile("id_matching_")
  dir.create(root)
  on.exit(unlink(root, recursive = TRUE))
  previous <- get_verbosity()
  on.exit(set_verbosity(previous), add = TRUE)
  set_verbosity("quiet")
  ids <- c("na", "0", "complement", "inversion")
  ref_path <- file.path(root, "reference.bim")
  prefix <- file.path(root, "source")
  writeLines(paste("1", ids, "0", seq_along(ids), "A", "G", sep = "\t"), ref_path)
  ref <- load_reference(ref_path)
  ref_cache <- file.path(root, "reference.rds")
  save_cache(ref, ref_cache)
  ref <- load_reference_cache(ref_cache)
  a1 <- c("A", "G", "T", "C")
  a2 <- c("G", "A", "C", "T")
  writeLines(paste("1", ids, "0", 100 + seq_along(ids), a1, a2, sep = "\t"), paste0(prefix, ".bim"))
  writeLines("f i 0 0 1 -9", paste0(prefix, ".fam"))
  writeBin(as.raw(c(0x6c, 0x1b, 0x01, 3, 3, 0, 1)), paste0(prefix, ".bed"))
  stats_path <- file.path(root, "stats.tsv")
  writeLines(c("SNP\ta1\ta2\tP\tz\tn\tbeta\teaf",
               paste(ids, a1, a2, ".01", "3", "100", "2", ".2", sep = "\t")), stats_path)
  s <- load_sumstats(stats_path, ref, match_by = "id")
  g <- load_genotype(prefix, ref, match_by = "id")
  expect_identical(snp(ref), ids)
  expect_identical(zvec(s), c(3, -3, 3, -3))
  expect_identical(beta_vec(s), c(2, -2, 2, -2))
  expect_equal(eaf_vec(s), c(.2, .8, .2, .8))
  expect_null(se_vec(s))
  expect_identical(is_allele_swapped(g), c(FALSE, TRUE, FALSE, TRUE))
  expect_identical(fetch_genotypes_int8(g, c(1, 2, 3, 4, 2)), matrix(c(0L, 2L, 2L, -1L, 2L), 1))
  expect_true(is_object_compatible(ref, s))
  expect_true(is_object_compatible(ref, g))
  s_cache <- file.path(root, "sumstats.rds")
  g_cache <- file.path(root, "genotype.rds")
  save_cache(s, s_cache)
  save_cache(g, g_cache)
  expect_identical(zvec(load_sumstats_cache(s_cache)), zvec(s))
  restored <- load_genotype_cache(g_cache)
  expect_identical(source_row0(restored), source_row0(g))
  expect_identical(is_allele_swapped(restored), is_allele_swapped(g))
  expect_identical(fetch_genotypes_int8(restored, 1:4), matrix(c(0L, 2L, 2L, -1L), 1))
})

test_that("ID reference ambiguity is panel-wide and subset-dependent", {
  root <- tempfile("id_ambiguity_")
  dir.create(root)
  on.exit(unlink(root, recursive = TRUE))
  previous <- get_verbosity()
  on.exit(set_verbosity(previous), add = TRUE)
  set_verbosity("quiet")
  ref_path <- file.path(root, "reference.bim")
  writeLines(c("1\tdup\t0\t1\tA\tG", "2\tdup\t0\t2\tT\tC"), ref_path)
  ref <- load_reference(ref_path)
  path <- file.path(root, "stats.tsv")
  writeLines(c("SNP\ta1\ta2\tP\tz\tn", "dup\tA\tG\t.01\t3\t100", "dup\tT\tC\t.01\t3\t100"), path)
  messages <- character()
  s <- withCallingHandlers(load_sumstats(path, ref, match_by = "id"), warning = function(w) {
    messages <<- c(messages, conditionMessage(w))
    invokeRestart("muffleWarning")
  })
  expect_false(any(is_present(s)))
  expect_true(any(grepl("2 slots in 1 duplicate ID key groups", messages, fixed = TRUE)))
  expect_equal(sum(grepl("no matching source rows", messages, fixed = TRUE)), 2)
  expect_error(load_sumstats(path, select_shards(ref, "1"), match_by = "id"), "Ambiguous.*dup")
  for (loader in list(load_sumstats, load_genotype)) {
    expect_error(loader("missing", ref, match_by = "ID"), "match_by")
    expect_error(loader("missing", ref, match_by = "id", allow_indel_swaps = TRUE), "match_by")
  }
})
